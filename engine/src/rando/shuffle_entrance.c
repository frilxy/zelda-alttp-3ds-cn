// Dungeon engine (Stage 2)
// ---------------------------------------------------------------------------

// Map a raw entrance-id to its dungeon index within the first `count` dungeons
// (the active pool), or -1 if not present. Bounding by `count` keeps Ganon's
// Tower (the last entry) untouched when its opt-in is off.
static int dungeon_of_entrance(uint8 ent_id, int count) {
  if (count > kEntranceDungeonCount) count = kEntranceDungeonCount;
  for (int i = 0; i < count; i++) {
    if (kDungeons[i].entrance_id == ent_id) return i;
  }
  return -1;
}

bool Entrance_IsDungeonActive(const RandoSettings *settings) {
  if (settings == NULL) return false;
  if (!settings->shuffle_dungeon_entrances) return false;
  // Same world-state scope as caves (Open/Standard).
  if (settings->world_state != kWorldState_Open &&
      settings->world_state != kWorldState_Standard) {
    return false;
  }
  return true;
}

int Entrance_ComputeDungeonPermutation(const RandoSettings *settings, uint64 seed,
                                       uint8 attempt,
                                       uint8 assign[kEntranceMaxInteriors]) {
  if (assign == NULL || !Entrance_IsDungeonActive(settings)) return 0;
  const int n = Entrance_DungeonPoolCount(settings);  // 10, or 11 with GT opt-in
  for (int i = 0; i < n; i++) assign[i] = (uint8)i;
  RandoRng rng;
  // Distinct salt from the cave RNG so cave and dungeon permutations are
  // independent when both axes are on (both still deterministic in
  // (seed, attempt) for save→regen).
  Rng_SeedFromU64(&rng, (seed ^ 0xD0D0D0D0D0D0D0D0ull) ^
                            ((uint64)attempt * 0x9E3779B97F4A7C15ull));
  for (int i = n - 1; i > 0; i--) {
    uint32 j = Rng_NextRange(&rng, (uint32)(i + 1));
    uint8 t = assign[i]; assign[i] = assign[j]; assign[j] = t;
  }
  return n;
}

void Entrance_ApplyEdgeOverrides(const uint8 *assign, int n) {
  Rando_BeginEntranceEdgeOverrides();
  if (assign == NULL) return;
  if (n > kEntranceDungeonCount) n = kEntranceDungeonCount;
  // Dungeon ix's door now leads to dungeon assign[ix]. The GATED door-edge whose
  // destination is ix's interior (lobby) region must now land at assign[ix]'s
  // interior region — keyed by the interior region so the door edge AND its gate
  // (e.g. MM/TR's medallion, which sits on Entrance→Lobby) move with the SOURCE
  // spot, not the loaded interior (task 2.8). For single-region dungeons the
  // interior key == entry region, so this is byte-identical to the old behavior.
  for (int ix = 0; ix < n; ix++) {
    uint16 from_lobby = Rando_FindRegionByName(dungeon_override_key(&kDungeons[ix]));
    int j = assign[ix];
    if (j < 0 || j >= kEntranceDungeonCount) continue;
    uint16 to_lobby = Rando_FindRegionByName(dungeon_override_key(&kDungeons[j]));
    if (from_lobby == 0xFFFF || to_lobby == 0xFFFF) continue;
    Rando_SetEntranceEdgeOverride(from_lobby, to_lobby);
  }
}

void Entrance_ClearEdgeOverrides(void) {
  Rando_ClearEntranceEdgeOverrides();
}

void Entrance_RemapDungeonDoors(const uint8 *assign, int n,
                                uint8 *overlay, uint32 len) {
  if (overlay == NULL || assign == NULL) return;
  if (n > kEntranceDungeonCount) n = kEntranceDungeonCount;
  // overlay holds vanilla dungeon entrance-ids here (the cave pass never touches
  // dungeon slots — the two id sets are disjoint). Redirect each dungeon door to
  // its image's entrance-id.
  for (uint32 d = 0; d < len; d++) {
    int i = dungeon_of_entrance(overlay[d], n);  // only the active pool [0,n)
    if (i < 0) continue;
    int j = assign[i];
    if (j < 0 || j >= n) continue;
    overlay[d] = kDungeons[j].entrance_id;
  }
}

// Coupling helper: given a SOURCE door's vanilla dungeon entrance-id, return the
// room the room-keyed exit search should target so the player returns to that
// SOURCE door (not the loaded dungeon's vanilla door). Returns 0 if the id is
// not a v1 dungeon door.
uint16 Entrance_DungeonSourceExitRoom(uint8 vanilla_entrance_id) {
  // Full table here (incl. GT): this is only consulted for a door the overlay
  // actually redirected, so an inactive GT door never reaches it (its caller
  // bails when the overlay value still equals vanilla).
  int i = dungeon_of_entrance(vanilla_entrance_id, kEntranceDungeonCount);
  if (i < 0) return 0;
  return kDungeons[i].room;
}

// ---------------------------------------------------------------------------
// Cross-category engine (Stage 3 / Crossed) — caves + dungeons in ONE pool.
// See design.md §9. Endpoint index space: e < kEntranceCaveInteriorCount is
// cave[e]; otherwise it's the (e - kEntranceCaveInteriorCount)-th CROSS-ELIGIBLE
// dungeon (single-inbound-edge dungeons only; TR/GT excluded — multi-source ⇒
// ambiguous predicate to inherit). assign[e] = the endpoint now behind e's door.
// ---------------------------------------------------------------------------
// Unreachable sink: removes a dungeon's original edge under Crossed. Was a
// hardcoded 63 — safe when the region table had ~40 rows, but the OW
// substrate grew it past 63 and the selfcheck caught the collision with a
// real component region. The sink is now the RESERVED top-of-cap id (codegen
// budgets real regions to kReachabilityMaxRegions - 1), which stays inside
// every cap-sized bitset (harmlessly settable) and can never be real.
#define kCrossVoidRegion (kReachabilityMaxRegions - 1)  // sink: removes original
                             // door-edge when a cave lands behind it. Safe:
                             // 63 < kReachabilityMaxRegions(256); no locs/edges.

// Fill `idx` with the kDungeons indices that are cross-eligible (entry region is
// the destination of EXACTLY ONE door-edge). Stable table order. Returns count.
static int cross_dungeon_list(uint8 idx[kEntranceDungeonCount]) {
  int n = 0;
  for (int i = 0; i < kEntranceDungeonCount; i++) {
    uint16 rid = Rando_FindRegionByName(kDungeons[i].entry_region_name);
    if (rid == 0xFFFF) continue;
    int inbound = 0;
    for (uint32 e = 0; e < kRandoEdgesCount; e++)
      if (kRandoEdges[e].to_region == rid) inbound++;
    if (inbound == 1) idx[n++] = (uint8)i;
  }
  return n;
}

// A dungeon's single door-edge: its from_region + predicate (offset/len). Only
// valid for cross-eligible (single-edge) dungeons.
static bool dungeon_door_edge(uint16 entry_region, uint16 *from,
                              uint32 *pred_off, uint16 *pred_len) {
  for (uint32 e = 0; e < kRandoEdgesCount; e++) {
    if (kRandoEdges[e].to_region == entry_region) {
      *from = kRandoEdges[e].from_region;
      *pred_off = kRandoEdges[e].predicate_offset;
      *pred_len = kRandoEdges[e].predicate_length;
      return true;
    }
  }
  return false;
}

// tracker-player-knowledge — bitmask (kRandoDungeon_* order, via each pool
// entry's lobby region dungeon_id binding) of dungeons whose IDENTITY the
// active entrance topology hides: the stage-2 pool (base 10 + GT opt-in) or,
// under cross-category, the cross-eligible dungeon list. Identity-mapped
// assignments are deliberately included — the player cannot know a door maps
// to itself. 0 when no dungeon-entrance axis is active.
uint16 Entrance_HiddenDungeonPoolMask(const RandoSettings *settings) {
  uint8 didx[kEntranceDungeonCount];
  int n = 0;
  const uint8 *rows = NULL;
  if (Entrance_IsCrossActive(settings)) {
    n = cross_dungeon_list(didx);
    rows = didx;
  } else if (Entrance_IsDungeonActive(settings)) {
    n = Entrance_DungeonPoolCount(settings);
  } else {
    return 0;
  }
  uint16 mask = 0;
  for (int i = 0; i < n && i < kEntranceDungeonCount; i++) {
    const RandoDungeon *d = &kDungeons[rows ? rows[i] : i];
    uint16 rid = Rando_FindRegionByName(dungeon_override_key(d));
    if (rid == 0xFFFF) continue;  // broken build; Entrance_SelfCheck hard-fails it
    for (uint32 r = 0; r < kRandoRegionsCount; r++) {
      if (kRandoRegions[r].id != rid) continue;
      if (kRandoRegions[r].dungeon_id < 16)
        mask |= (uint16)(1u << kRandoRegions[r].dungeon_id);
      break;
    }
  }
  return mask;
}

bool Entrance_IsCrossActive(const RandoSettings *settings) {
  if (settings == NULL || !settings->cross_category) return false;
  // Cross is the "mix caves + dungeons" master mode; the Crossed preset sets
  // cave + dungeon + cross together. Open/Standard only (same as the others).
  if (!settings->shuffle_cave_entrances || !settings->shuffle_dungeon_entrances)
    return false;
  return settings->world_state == kWorldState_Open ||
         settings->world_state == kWorldState_Standard;
}

// Combined-pool size = caves + cross-eligible dungeons.
static int cross_pool_count(void) {
  uint8 didx[kEntranceDungeonCount];
  return kEntranceCaveInteriorCount + cross_dungeon_list(didx);
}

int Entrance_ComputeCrossPermutation(const RandoSettings *settings, uint64 seed,
                                     uint8 attempt, uint8 assign[kEntranceMaxInteriors]) {
  if (assign == NULL || !Entrance_IsCrossActive(settings)) return 0;
  int n = cross_pool_count();
  if (n > kEntranceMaxInteriors) return 0;  // safety (47 << 64)
  for (int i = 0; i < n; i++) assign[i] = (uint8)i;
  RandoRng rng;
  Rng_SeedFromU64(&rng, (seed ^ 0xC2055CA7E5C2055Cull) ^
                            ((uint64)attempt * 0x9E3779B97F4A7C15ull));
  for (int i = n - 1; i > 0; i--) {
    uint32 j = Rng_NextRange(&rng, (uint32)(i + 1));
    uint8 t = assign[i]; assign[i] = assign[j]; assign[j] = t;
  }
  return n;
}

// Install the 4-case cross-class overrides from the combined permutation.
void Entrance_ApplyCrossOverrides(const uint8 *assign, int n) {
  Rando_BeginEntranceRegionOverrides();
  Rando_BeginEntranceEdgeOverrides();
  if (assign == NULL) return;
  uint8 didx[kEntranceDungeonCount];
  int ndun = cross_dungeon_list(didx);
  const int ncave = kEntranceCaveInteriorCount;
  if (n != ncave + ndun) return;  // pool mismatch — bail (no partial overrides)

  for (int e = 0; e < n; e++) {
    int y = assign[e];
    bool e_cave = (e < ncave);
    bool y_cave = (y < ncave);
    // Resolve endpoint e's door (region R_e + predicate P_e) and, if e is a
    // dungeon, its entry region G_e.
    // G_e is the dungeon's INTERIOR (lobby) region — the gated door edge's
    // to_region. dungeon_door_edge(G_e) then finds THAT edge, returning its
    // from_region (R_e = the spot/waypoint) and predicate (P_e = the door gate,
    // e.g. MM's medallion). Keying on the interior (not the pre-door waypoint)
    // makes the gate travel with the overworld spot (task 2.8). For single-region
    // dungeons interior == entry, so this is unchanged.
    uint16 R_e = 0xFFFF, G_e = 0xFFFF; uint32 Pe_off = 0; uint16 Pe_len = 0;
    if (e_cave) {
      R_e = Rando_FindRegionByName(kCaveInteriors[e].region_name);
      cave_source_pred(e, &Pe_off, &Pe_len);
    } else {
      const RandoDungeon *de = &kDungeons[didx[e - ncave]];
      G_e = Rando_FindRegionByName(dungeon_override_key(de));
      dungeon_door_edge(G_e, &R_e, &Pe_off, &Pe_len);
    }
    if (y_cave) {
      // Target is a cave: override its locations to e's door region and source
      // predicate. For cave sources, P_e comes from entrance_registry.yaml
      // can_enter; for dungeon sources, it is the dungeon door edge predicate.
      const RandoCaveInterior *yc = &kCaveInteriors[y];
      for (int k = 0; k < yc->location_count; k++) {
        Rando_SetEntranceRegionOverridePred(yc->location_ids[k], R_e, Pe_off, Pe_len);
      }
      // If e is a dungeon, its original door-edge must be REMOVED (a cave is
      // behind it now) — redirect e's edge to the void sink.
      if (!e_cave && G_e != 0xFFFF) Rando_SetEntranceEdgeOverride(G_e, kCrossVoidRegion);
    } else {
      // Target is a dungeon — land at its INTERIOR (lobby) region G_y.
      const RandoDungeon *dy = &kDungeons[didx[y - ncave]];
      uint16 G_y = Rando_FindRegionByName(dungeon_override_key(dy));
      if (G_y == 0xFFFF) continue;
      if (e_cave) {
        // Dungeon behind a cave door: ADD an edge cave-region → G_y that keeps
        // the cave source gate with the door slot.
        Rando_AddEntranceEdge(R_e, G_y, Pe_off, Pe_len);
      } else {
        // Dungeon behind a dungeon door: remap e's edge to G_y (keeps P_e).
        if (G_e != 0xFFFF) Rando_SetEntranceEdgeOverride(G_e, G_y);
      }
    }
  }
}

// Build the unified cross door overlay: each door slot → its target endpoint's
// representative entrance-id (cave or dungeon).
void Entrance_BuildCrossOverlay(const uint8 *assign, int n, const uint8 *vanilla,
                                uint32 len, uint8 *overlay) {
  if (vanilla == NULL || overlay == NULL) return;
  memcpy(overlay, vanilla, len);
  if (assign == NULL) return;
  uint8 didx[kEntranceDungeonCount];
  int ndun = cross_dungeon_list(didx);
  const int ncave = kEntranceCaveInteriorCount;
  if (n != ncave + ndun) return;
  for (uint32 d = 0; d < len; d++) {
    // Determine the door's source endpoint. Caves resolve by DOOR ROW (`d`) —
    // the entrance id is ambiguous across the split shop entries — and dungeons,
    // whose ids are unique, by id.
    int e = -1;
    int ci = entry_of_door_row((uint16)d);
    if (ci >= 0) {
      e = ci;  // cave endpoint
    } else {
      int dd = dungeon_of_entrance(vanilla[d], kEntranceDungeonCount);
      if (dd >= 0) {
        for (int q = 0; q < ndun; q++) if (didx[q] == dd) { e = ncave + q; break; }
      }
    }
    if (e < 0) continue;  // not a shuffled door (or a TR/GT door — left vanilla)
    int y = assign[e];
    if (y < 0 || y >= n) continue;
    if (y < ncave) overlay[d] = kCaveInteriors[y].entrance_ids[0];
    else overlay[d] = kDungeons[didx[y - ncave]].entrance_id;
  }
}

// True iff door-slot's vanilla entrance-id is a CAVE interior (cached-exit
// class). Used by the runtime to force the cached exit for a cave-source door
// that now loads a dungeon (cross-category). 0 = not a cave door.
bool Entrance_IsCaveEntranceId(uint8 vanilla_entrance_id) {
  return interior_of_entrance(vanilla_entrance_id) >= 0;
}

// ---------------------------------------------------------------------------
// Cross + Decoupled (Stage 4) — one-way exits over the MIXED cross pool.
// π_out is an independent permutation of the combined endpoint space; exiting
// the interior behind door e emerges at endpoint net[e]'s door, which may be a
// CAVE (replay its baked arrival) or a DUNGEON (kExitData room search). Like the
// other decoupled modes it adds NO logic edges — coupled-equivalent reachability
// is correct + conservative since every emerge spot is on the connected overworld.
// ---------------------------------------------------------------------------
bool Entrance_IsCrossDecoupledActive(const RandoSettings *settings) {
  return settings != NULL && settings->decoupled && Entrance_IsCrossActive(settings);
}

// Forward decl — defined with the dungeon-decoupled compute below.
static bool dungeon_is_water_isolated(int idx);

int Entrance_ComputeCrossDecoupledExit(const RandoSettings *settings, uint64 seed,
                                       uint8 attempt, uint8 exit_assign[kEntranceMaxInteriors]) {
  if (exit_assign == NULL || !Entrance_IsCrossDecoupledActive(settings)) return 0;
  int n = cross_pool_count();
  if (n > kEntranceMaxInteriors) return 0;
  for (int i = 0; i < n; i++) exit_assign[i] = (uint8)i;
  // Pin water-isolated DUNGEON endpoints (Ice/Swamp) out of the exit shuffle —
  // same one-way-strand risk as dungeon-decoupled. Cross-pool
  // positions [0,ncave) are caves (walkable); [ncave,n) are dungeons via didx.
  const int ncave = kEntranceCaveInteriorCount;
  uint8 didx[kEntranceDungeonCount];
  cross_dungeon_list(didx);
  uint8 mobile[kEntranceMaxInteriors];
  int nmob = 0;
  for (int i = 0; i < n; i++) {
    bool pinned = (i >= ncave) && dungeon_is_water_isolated(didx[i - ncave]);
    if (!pinned) mobile[nmob++] = (uint8)i;
  }
  RandoRng rng;
  // Distinct salt from cross-ENTRY (0xC2055…), cave-decoupled (0xE511…) and
  // dungeon-decoupled (0xD1CE…) so the exit permutation is independent.
  Rng_SeedFromU64(&rng, (seed ^ 0xC2055DEC0DEDC205ull) ^
                            ((uint64)attempt * 0x9E3779B97F4A7C15ull));
  for (int k = nmob - 1; k > 0; k--) {
    uint32 m = Rng_NextRange(&rng, (uint32)(k + 1));
    uint8 t = exit_assign[mobile[k]];
    exit_assign[mobile[k]] = exit_assign[mobile[m]];
    exit_assign[mobile[m]] = t;
  }
  return n;
}

// Source endpoint index of the door at row `lx` in the cross combined pool
// (cave interior, or ncave + cross-dungeon slot). -1 if not a cross-pool door.
// Caves resolve by door row (the entrance id is ambiguous across the split shop
// entries); dungeons, whose ids are unique, by the door's vanilla entrance id.
static int cross_source_endpoint(uint16 lx, uint8 vanilla_entrance_id) {
  int ci = entry_of_door_row(lx);
  if (ci >= 0) return ci;
  uint8 didx[kEntranceDungeonCount];
  int ndun = cross_dungeon_list(didx);
  int dd = dungeon_of_entrance(vanilla_entrance_id, kEntranceDungeonCount);
  if (dd >= 0)
    for (int q = 0; q < ndun; q++)
      if (didx[q] == dd) return kEntranceCaveInteriorCount + q;
  return -1;
}

// Decode a cross endpoint → exit kind: 1 = cave (*value = cave interior),
// 2 = dungeon (*value = dungeon entry ROOM), 0 = out of range.
static int cross_endpoint_kind(int endpoint, uint16 *value) {
  const int ncave = kEntranceCaveInteriorCount;
  if (endpoint < 0) return 0;
  if (endpoint < ncave) { if (value) *value = (uint16)endpoint; return 1; }
  uint8 didx[kEntranceDungeonCount];
  int ndun = cross_dungeon_list(didx);
  int q = endpoint - ncave;
  if (q < ndun) { if (value) *value = kDungeons[didx[q]].room; return 2; }
  return 0;
}

// Runtime: for the source door at row `lx` (vanilla entrance id
// `vanilla_entrance_id`) under cross-decoupled, the exit target kind (1 = cave
// interior, 2 = dungeon room) into *value, or 0 for a self-map / non-pool door
// (caller keeps the coupled return-to-source).
int Entrance_CrossDecoupledExit(const uint8 *cross_net, int n, uint16 lx,
                                uint8 vanilla_entrance_id, uint16 *value) {
  if (cross_net == NULL || n <= 0) return 0;
  int e = cross_source_endpoint(lx, vanilla_entrance_id);
  if (e < 0 || e >= n) return 0;
  int t = cross_net[e];
  if (t < 0 || t >= n || t == e) return 0;  // self-map → coupled return
  return cross_endpoint_kind(t, value);
}

