// Public: an interior's declared door rows (count; *out_rows may be NULL when
// out of range). Exists so the runtime self-check can cross-validate the
// committed row map against the LIVE asset tables — the row->entry map is a
// constant, and the offline validator is skipped in assetless profiles.
int Entrance_CaveInteriorDoorRows(int interior, const uint8 **out_rows) {
  if (out_rows) *out_rows = NULL;
  if (interior < 0 || interior >= kEntranceCaveInteriorCount) return 0;
  if (out_rows) *out_rows = kCaveInteriors[interior].door_rows;
  return kCaveInteriors[interior].door_row_count;
}

// Public: does `interior` declare `ent_id`? Companion to the above — lets the
// runtime check assert that each door row's LIVE entrance id is one its entry
// claims, without exposing the table itself.
bool Entrance_InteriorDeclaresEntranceId(int interior, uint8 ent_id) {
  if (interior < 0 || interior >= kEntranceCaveInteriorCount) return false;
  for (int k = 0; k < kCaveInteriors[interior].entrance_count; k++)
    if (kCaveInteriors[interior].entrance_ids[k] == ent_id) return true;
  return false;
}

// Public: the representative (first) entrance-id of cave interior `interior`,
// or 0 if out of range. The decoupled exit replays this door's arrival, and
// uses its kEntranceData_rooms/doorSettings for the Y-adjust (spike iter4).
uint8 Entrance_CaveRepresentativeId(int interior) {
  if (interior < 0 || interior >= kEntranceCaveInteriorCount) return 0;
  return kCaveInteriors[interior].entrance_ids[0];
}

// Public: the cave interior the door at overworld row `lx` now LOADS under the
// installed entry permutation, or -1 when the door reaches no cave.
//
// This is the D4 chain in one place: door row -> source endpoint -> assignment
// -> destination entry. `net`/`n` is the installed entry permutation
// (Entrance_RuntimeInstall's g_entry_net); pass NULL/0 for "no layout", which
// makes the assignment the identity and reduces this to Entrance_InteriorOfDoorRow.
// `cross` selects the endpoint space: under Crossed the permutation runs over the
// COMBINED cave+dungeon endpoints, so a dungeon door can be the source of a cave
// destination (and a cave door's target can be a dungeon, which returns -1).
// `vanilla_entrance_id` is the door's PRISTINE entrance id, needed only to
// resolve a dungeon source (dungeon ids are unique; cave sources go by row).
int Entrance_DestCaveOfDoorRow(const uint8 *net, int n, bool cross, uint16 lx,
                               uint8 vanilla_entrance_id) {
  int src = cross ? cross_source_endpoint(lx, vanilla_entrance_id)
                  : entry_of_door_row(lx);
  if (src < 0) return -1;
  int dst = src;
  if (net != NULL && n > 0 && src < n) dst = net[src];
  // Out of the cave range = a dungeon endpoint under Crossed: no cave loaded.
  if (dst < 0 || dst >= kEntranceCaveInteriorCount) return -1;
  return dst;
}

