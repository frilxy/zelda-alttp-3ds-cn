void Entrance_WriteCrossSpoilerJson(void *file, const uint8 *assign, int n) {
  FILE *f = (FILE *)file;
  if (f == NULL || assign == NULL || n <= 0) return;
  uint8 didx[kEntranceDungeonCount];
  int ndun = cross_dungeon_list(didx);
  if (n != kEntranceCaveInteriorCount + ndun) return;
  fprintf(f, "  \"cross_entrance_mapping\": [\n");
  for (int e = 0; e < n; e++) {
    int y = assign[e];
    if (y < 0 || y >= n) y = e;
    fprintf(f, "    {\"door\": \"%s\", \"leads_to\": \"%s\"}%s\n",
            cross_endpoint_name(e, didx, ndun), cross_endpoint_name(y, didx, ndun),
            (e + 1 < n) ? "," : "");
  }
  fprintf(f, "  ],\n");
}

void Entrance_WriteCrossSpoilerText(void *file, const uint8 *assign, int n) {
  FILE *f = (FILE *)file;
  if (f == NULL || assign == NULL || n <= 0) return;
  uint8 didx[kEntranceDungeonCount];
  int ndun = cross_dungeon_list(didx);
  if (n != kEntranceCaveInteriorCount + ndun) return;
  fprintf(f, "Cross-category entrance mapping (caves + dungeons, coupled):\n");
  for (int e = 0; e < n; e++) {
    int y = assign[e];
    if (y < 0 || y >= n) y = e;
    if (y == e) continue;  // list only the moved doors
    fprintf(f, "  %s door -> %s\n",
            cross_endpoint_name(e, didx, ndun), cross_endpoint_name(y, didx, ndun));
  }
}

// ---------------------------------------------------------------------------
// Self-check (pure; no live assets). Uses only the static table + logic_data.
// ---------------------------------------------------------------------------
static const RandoLocationDef *find_location(uint16 id) {
  for (uint32 i = 0; i < kRandoLocationsCount; i++) {
    if (kRandoLocations[i].id == id) return &kRandoLocations[i];
  }
  return NULL;
}

void Entrance_SelfCheck(void) {
  // (0) The cross engine uses kCrossVoidRegion (63) as an unreachable sink to
  //     remove a dungeon's original door-edge (design.md §9 case 3). That only
  //     works if NO real region owns id 63 — otherwise the void redirect would
  //     silently make a live region the sink. Guard it: if a future
  //     logic-graph edit ever assigns region 63, this fails the build's selftest
  //     instead of shipping a quietly-wrong reachability model.
  if (strcmp(Rando_GetRegionName(kCrossVoidRegion), "(unbound)") != 0) {
    fprintf(stderr, "Entrance_SelfCheck: kCrossVoidRegion (%d) collides with real "
                    "region '%s' — pick an unused sink id\n",
            kCrossVoidRegion, Rando_GetRegionName(kCrossVoidRegion));
    exit(2);
  }

  // (1) DOOR ROWS PARTITION the pool, and every interior's room is in the
  //     cached-exit cave class [0x100,0x180)\{0x104} (so a shuffled cave can
  //     never hit the room-keyed exit SEARCH).
  //
  //     This check used to assert that every ENTRANCE ID resolved back to its
  //     own interior, which hard-fails the moment two entries share an id. That
  //     sharing is now legitimate and load-bearing: the four Dark World shop
  //     doors are four pool entries that all load room 0x10F through id 0x60.
  //     The invariant that actually has to hold is the door-row one — each row
  //     belongs to exactly one entry — because the row is what resolves a source
  //     door. ("No row dropped" needs the vanilla asset table and is checked by
  //     assets/scripts/gen_entrance_door_rows.py --check.)
  {
    int row_owner[256];
    for (int r = 0; r < 256; r++) row_owner[r] = -1;
    for (int i = 0; i < kEntranceCaveInteriorCount; i++) {
      uint16 room = kCaveInteriors[i].room;
      if (!(room >= 0x100 && room < 0x180 && room != 0x104)) {
        fprintf(stderr, "Entrance_SelfCheck: interior %d room 0x%03X outside cave "
                        "class [0x100,0x180)\\{0x104}\n", i, room);
        exit(2);
      }
      if (kCaveInteriors[i].entrance_count == 0 ||
          kCaveInteriors[i].door_row_count == 0) {
        fprintf(stderr, "Entrance_SelfCheck: interior %d ('%s') has %u entrance-ids "
                        "and %u door rows; both must be non-empty\n",
                i, kCaveInteriors[i].name,
                (unsigned)kCaveInteriors[i].entrance_count,
                (unsigned)kCaveInteriors[i].door_row_count);
        exit(2);
      }
      for (int k = 0; k < kCaveInteriors[i].door_row_count; k++) {
        uint8 r = kCaveInteriors[i].door_rows[k];
        if (row_owner[r] >= 0) {
          fprintf(stderr, "Entrance_SelfCheck: door row 0x%02X claimed by interiors "
                          "%d ('%s') and %d ('%s') — rows must partition the pool\n",
                  r, row_owner[r], kCaveInteriors[row_owner[r]].name, i,
                  kCaveInteriors[i].name);
          exit(2);
        }
        row_owner[r] = i;
        if (entry_of_door_row(r) != i) {
          fprintf(stderr, "Entrance_SelfCheck: door row 0x%02X resolves to interior %d, "
                          "want %d\n", r, entry_of_door_row(r), i);
          exit(2);
        }
      }
    }
    // Entries that share an ENTRANCE ID must declare the same ROOM — the id
    // determines the room through kEntranceData_rooms, so a disagreement means a
    // door row is attributed to the wrong entry. (The converse is NOT required:
    // two ids may load one room, e.g. 0x58/0x5A both reach room 0x112.)
    //
    // And a shared id must never be a FALL-HOLE id (0x76-0x81):
    // Rando_RecordEnteredFallhole has no door row to key on — a fall writes
    // which_entrance directly — so it resolves by id alone and could not tell
    // two sharers apart. Enforced here as well as in gen_entrance_table.py so a
    // hand-edit of the generated block cannot slip past.
    for (int i = 0; i < kEntranceCaveInteriorCount; i++) {
      for (int k = 0; k < kCaveInteriors[i].entrance_count; k++) {
        uint8 id = kCaveInteriors[i].entrance_ids[k];
        for (int j = i + 1; j < kEntranceCaveInteriorCount; j++) {
          bool shares = false;
          for (int m = 0; m < kCaveInteriors[j].entrance_count; m++)
            if (kCaveInteriors[j].entrance_ids[m] == id) shares = true;
          if (!shares) continue;
          if (kCaveInteriors[i].room != kCaveInteriors[j].room) {
            fprintf(stderr, "Entrance_SelfCheck: interiors %d/%d share entrance-id "
                            "0x%02X but declare rooms 0x%03X/0x%03X\n",
                    i, j, id, kCaveInteriors[i].room, kCaveInteriors[j].room);
            exit(2);
          }
          if (id >= 0x76 && id <= 0x81) {
            fprintf(stderr, "Entrance_SelfCheck: interiors %d/%d share entrance-id "
                            "0x%02X, which is in the fall-hole range 0x76-0x81; "
                            "Rando_RecordEnteredFallhole keys on the id alone\n",
                    i, j, id);
            exit(2);
          }
        }
      }
    }
  }
  if (kRandoCaveSourcePredsCount != kEntranceCaveInteriorCount) {
    fprintf(stderr, "Entrance_SelfCheck: cave source predicate count %u != %d\n",
            (unsigned)kRandoCaveSourcePredsCount, kEntranceCaveInteriorCount);
    exit(2);
  }

  // (2) Registry↔logic cross-validation: every cave-location's registry region
  //     must equal its region_id in the generated logic table. This catches
  //     registry/logic drift at build time (the otherwise playtest-only seam).
  for (int i = 0; i < kEntranceCaveInteriorCount; i++) {
    const RandoCaveInterior *it = &kCaveInteriors[i];
    if (it->location_count == 0 || it->region_name == NULL) continue;
    uint16 rid = Rando_FindRegionByName(it->region_name);
    if (rid == 0xFFFF) {
      fprintf(stderr, "Entrance_SelfCheck: interior %d region '%s' not found in "
                      "logic regions\n", i, it->region_name);
      exit(2);
    }
    for (int k = 0; k < it->location_count; k++) {
      const RandoLocationDef *loc = find_location(it->location_ids[k]);
      if (loc == NULL) {
        fprintf(stderr, "Entrance_SelfCheck: cave location %u not in logic table\n",
                it->location_ids[k]);
        exit(2);
      }
      if (loc->region_id != rid) {
        fprintf(stderr, "Entrance_SelfCheck: location %u region mismatch — "
                        "registry '%s'(%u) vs logic region_id %u (interior %d). "
                        "Registry/logic drift; fix entrance_registry.yaml or logic.\n",
                it->location_ids[k], it->region_name, rid, loc->region_id, i);
        exit(2);
      }
    }
  }

  // (2b) shop_loc_base is well-formed and its three slots are BOUND as this
  //      entry's locations. The binding is what brings the entry under (2)
  //      above — the region cross-validation the shop split depends on — and
  //      what makes Entrance_ApplyRegionOverrides rebind the shop to whichever
  //      door reaches it. A base without its locations would hand the player a
  //      slot the logic still binds to its vanilla region. Asserted in
  //      gen_entrance_table.py too, so a hand-edit of the generated block
  //      cannot slip past the data guard (same discipline as the fall-hole
  //      shared-id rule above).
  for (int i = 0; i < kEntranceCaveInteriorCount; i++) {
    uint16 base = kCaveInteriors[i].shop_loc_base;
    if (base == 0xFFFFu) continue;
    if (base < 237 || base + 2 > 263 || (base - 237) % 3 != 0 || base == 255) {
      fprintf(stderr, "Entrance_SelfCheck: interior %d shop_loc_base %u is not a "
                      "cave-shop block base (237+3k, k<9, excluding the non-cave "
                      "Light World Death Mountain shop at 255)\n", i, base);
      exit(2);
    }
    for (uint16 k = 0; k < 3; k++) {
      bool bound = false;
      for (int m = 0; m < kCaveInteriors[i].location_count; m++)
        if (kCaveInteriors[i].location_ids[m] == (uint16)(base + k)) bound = true;
      if (!bound) {
        fprintf(stderr, "Entrance_SelfCheck: interior %d declares shop base %u but "
                        "does not list slot %u in its locations — the region "
                        "rebinding would silently not happen\n", i, base, base + k);
        exit(2);
      }
    }
    for (int j = i + 1; j < kEntranceCaveInteriorCount; j++) {
      if (kCaveInteriors[j].shop_loc_base == base) {
        fprintf(stderr, "Entrance_SelfCheck: interiors %d/%d both claim shop base "
                        "%u\n", i, j, base);
        exit(2);
      }
    }
  }

  // (3) Permutation is a bijection of [0,N).
  RandoSettings s;
  Settings_SetDefaults(&s);
  s.shuffle_cave_entrances = 1;
  s.world_state = kWorldState_Open;
  uint8 assign[kEntranceMaxInteriors];
  int n = Entrance_ComputePermutation(&s, 0xC0FFEEu, 0, assign);
  if (n != kEntranceCaveInteriorCount) {
    fprintf(stderr, "Entrance_SelfCheck: permutation count %d != %d\n",
            n, kEntranceCaveInteriorCount);
    exit(2);
  }
  {
    uint8 seen[kEntranceMaxInteriors];
    memset(seen, 0, sizeof(seen));
    for (int i = 0; i < n; i++) {
      if (assign[i] >= n || seen[assign[i]]) {
        fprintf(stderr, "Entrance_SelfCheck: permutation is not a bijection\n");
        exit(2);
      }
      seen[assign[i]] = 1;
    }
  }

  // (4) Determinism: same (seed, attempt) ⇒ same permutation; different attempt
  //     ⇒ (almost surely) different.
  {
    uint8 a2[kEntranceMaxInteriors];
    Entrance_ComputePermutation(&s, 0xC0FFEEu, 0, a2);
    if (memcmp(assign, a2, n) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: permutation not deterministic\n");
      exit(2);
    }
  }

  // (5) Inactive settings ⇒ no permutation (default-off invariant).
  {
    RandoSettings off;
    Settings_SetDefaults(&off);  // shuffle_cave_entrances default 0
    uint8 a3[kEntranceMaxInteriors];
    if (Entrance_ComputePermutation(&off, 1, 0, a3) != 0 ||
        Entrance_IsActive(&off)) {
      fprintf(stderr, "Entrance_SelfCheck: inactive settings must not shuffle\n");
      exit(2);
    }
    // Inverted/Retro are out of Stage 1 scope even with the axis on.
    RandoSettings inv = s; inv.world_state = kWorldState_Inverted;
    RandoSettings ret = s; ret.world_state = kWorldState_Retro;
    if (Entrance_IsActive(&inv) || Entrance_IsActive(&ret)) {
      fprintf(stderr, "Entrance_SelfCheck: Inverted/Retro must be out of scope\n");
      exit(2);
    }
  }

  // (6) Region-override closed form, asserted via the getter: a forced 2-swap of
  //     two interiors with locations and DIFFERENT regions exchanges their
  //     location regions. interior 10 aginah_cave (LightWorld_South, loc 175)
  //     <-> interior 8 village_chest_game (DarkWorld_NorthWest, locs 215/217).
  {
    uint16 lws = Rando_FindRegionByName("LightWorld_South");
    uint16 dwnw = Rando_FindRegionByName("DarkWorld_NorthWest");
    if (lws == 0xFFFF || dwnw == 0xFFFF) {
      fprintf(stderr, "Entrance_SelfCheck: region name resolution failed\n");
      exit(2);
    }
    uint8 sw[kEntranceMaxInteriors];
    for (int i = 0; i < kEntranceCaveInteriorCount; i++) sw[i] = (uint8)i;
    sw[10] = 8; sw[8] = 10;
    Entrance_ApplyRegionOverrides(sw, kEntranceCaveInteriorCount);
    // Aginah's loc (175) now reached via village's door ⇒ DWNW; village's loc
    // (215) via aginah's door ⇒ LWS.
    if (Rando_GetEntranceRegionOverride(175) != dwnw ||
        Rando_GetEntranceRegionOverride(215) != lws) {
      fprintf(stderr, "Entrance_SelfCheck: region-override closed form wrong "
                      "(175→%u want %u, 215→%u want %u)\n",
              Rando_GetEntranceRegionOverride(175), dwnw,
              Rando_GetEntranceRegionOverride(215), lws);
      exit(2);
    }
    // Identity permutation ⇒ every cave-location override equals its own region
    // (a no-op), and Clear deactivates so the getter returns 0xFFFF.
    uint8 id[kEntranceMaxInteriors];
    for (int i = 0; i < kEntranceCaveInteriorCount; i++) id[i] = (uint8)i;
    Entrance_ApplyRegionOverrides(id, kEntranceCaveInteriorCount);
    if (Rando_GetEntranceRegionOverride(175) != lws) {
      fprintf(stderr, "Entrance_SelfCheck: identity override must keep own region\n");
      exit(2);
    }
    Entrance_ClearRegionOverrides();
    if (Rando_GetEntranceRegionOverride(175) != 0xFFFF) {
      fprintf(stderr, "Entrance_SelfCheck: Clear must deactivate overrides\n");
      exit(2);
    }
  }

  // (6b) The same closed form for SHOP slots — design D5's "region binding falls
  //      out" is the whole reason shopsanity can compose with cave-entrance
  //      shuffle, and nothing else asserts it. The spoiler prints each location's
  //      STATIC logic region (for every location type, not just shops), so a
  //      spoiler read can neither confirm nor refute this; only the override
  //      getter can. Swap the Dark World Potion Shop's entry with the Light World
  //      Lake Hylia Shop's and require their three-slot blocks to trade regions.
  //      Entry indices are hard-coded like (6) above (append-only ordering keeps
  //      them valid) but are name-checked first, so a reorder fails loudly
  //      instead of silently testing some other pair.
  {
    const int kPotion = 43, kLakeHylia = 21;
    if (strcmp(kCaveInteriors[kPotion].name, "general_store_3_potion") != 0 ||
        strcmp(kCaveInteriors[kLakeHylia].name, "general_store_2") != 0) {
      fprintf(stderr, "Entrance_SelfCheck: shop region-binding check is pinned to "
                      "interior indices %d/%d, which now hold '%s'/'%s' — the "
                      "interiors list was reordered (it must be append-only)\n",
              kPotion, kLakeHylia, kCaveInteriors[kPotion].name,
              kCaveInteriors[kLakeHylia].name);
      exit(2);
    }
    uint16 dwne = Rando_FindRegionByName("DarkWorld_NorthEast");
    uint16 lws2 = Rando_FindRegionByName("LightWorld_South");
    uint8 sw[kEntranceMaxInteriors];
    for (int i = 0; i < kEntranceCaveInteriorCount; i++) sw[i] = (uint8)i;
    sw[kPotion] = (uint8)kLakeHylia; sw[kLakeHylia] = (uint8)kPotion;
    Entrance_ApplyRegionOverrides(sw, kEntranceCaveInteriorCount);
    for (uint16 k = 0; k < 3; k++) {
      // Lake Hylia's slots (261..263) are now reached through the Potion door.
      if (Rando_GetEntranceRegionOverride((uint16)(261 + k)) != dwne ||
          // ...and the Potion slots (237..239) through Lake Hylia's door.
          Rando_GetEntranceRegionOverride((uint16)(237 + k)) != lws2) {
        fprintf(stderr, "Entrance_SelfCheck: shop slots did not rebind to the "
                        "shuffled door's region (%u→%u want %u, %u→%u want %u)\n",
                261 + k, Rando_GetEntranceRegionOverride((uint16)(261 + k)), dwne,
                237 + k, Rando_GetEntranceRegionOverride((uint16)(237 + k)), lws2);
        exit(2);
      }
    }
    Entrance_ClearRegionOverrides();
  }

  // (6c) The SAME shop rebinding through the CROSS-category path. Under Crossed
  //      the placer's binding comes from Entrance_ApplyCrossOverrides, a
  //      DIFFERENT function over a combined cave+dungeon endpoint space — (6b)
  //      above would pass while that path bound nothing, and the runtime would
  //      still hand shops over via the installed permutation. That is the
  //      placement/runtime disagreement this whole change exists to avoid, so
  //      pin both functions, not one.
  {
    const int kPotion = 43, kLakeHylia = 21;   // name-checked in (6b) above
    uint16 dwne = Rando_FindRegionByName("DarkWorld_NorthEast");
    uint16 lws2 = Rando_FindRegionByName("LightWorld_South");
    uint8 didx[kEntranceDungeonCount];
    int ndun = cross_dungeon_list(didx);
    int n_cross = kEntranceCaveInteriorCount + ndun;
    if (n_cross > kEntranceMaxInteriors) {
      fprintf(stderr, "Entrance_SelfCheck: cross pool %d exceeds %d\n",
              n_cross, kEntranceMaxInteriors);
      exit(2);
    }
    uint8 cw[kEntranceMaxInteriors];
    for (int i = 0; i < n_cross; i++) cw[i] = (uint8)i;
    cw[kPotion] = (uint8)kLakeHylia; cw[kLakeHylia] = (uint8)kPotion;
    Entrance_ApplyCrossOverrides(cw, n_cross);
    for (uint16 k = 0; k < 3; k++) {
      if (Rando_GetEntranceRegionOverride((uint16)(261 + k)) != dwne ||
          Rando_GetEntranceRegionOverride((uint16)(237 + k)) != lws2) {
        fprintf(stderr, "Entrance_SelfCheck: shop slots did not rebind under the "
                        "CROSS-category override path (%u→%u want %u, %u→%u want "
                        "%u)\n",
                261 + k, Rando_GetEntranceRegionOverride((uint16)(261 + k)), dwne,
                237 + k, Rando_GetEntranceRegionOverride((uint16)(237 + k)), lws2);
        exit(2);
      }
    }
    Entrance_ClearRegionOverrides();
    Entrance_ClearEdgeOverrides();
  }

  // (7) Door overlay: build a synthetic vanilla table INDEXED BY DOOR ROW, since
  //     that is what the overlay now keys on. Every declared row gets one of its
  //     interior's entrance-ids (cycling through them, so the non-representative
  //     ids of multi-door interiors are still exercised — and, now, PROVEN
  //     irrelevant to source resolution); unclaimed rows hold a non-cave
  //     sentinel and must pass through untouched. Each claimed row must rewrite
  //     to the representative id of ITS interior's image.
  //
  //     The array is sized to the full u8 door-row space rather than a
  //     hand-counted 80 — the old bound was one split away from a stack
  //     overflow, with no check.
  {
    enum { kSelfCheckRows = 256 };
    static uint8 van[kSelfCheckRows];
    static uint8 ov[kSelfCheckRows];
    static int slot_interior[kSelfCheckRows];
    int max_row = -1;
    for (int r = 0; r < kSelfCheckRows; r++) { van[r] = 0xFE; slot_interior[r] = -1; }
    for (int i = 0; i < kEntranceCaveInteriorCount; i++) {
      for (int k = 0; k < kCaveInteriors[i].door_row_count; k++) {
        uint8 r = kCaveInteriors[i].door_rows[k];
        van[r] = kCaveInteriors[i].entrance_ids[k % kCaveInteriors[i].entrance_count];
        slot_interior[r] = i;
        if ((int)r > max_row) max_row = (int)r;
      }
    }
    if (max_row < 0 || max_row + 2 > kSelfCheckRows) {
      fprintf(stderr, "Entrance_SelfCheck: door-row span %d does not fit the %d-row "
                      "synthetic table\n", max_row, kSelfCheckRows);
      exit(2);
    }
    int total = max_row + 2;   // + one trailing unclaimed row as the sentinel
    Entrance_BuildDoorOverlay(assign, n, van, (uint32)total, ov);
    for (int d = 0; d < total; d++) {
      if (slot_interior[d] < 0) {
        if (ov[d] != van[d]) {
          fprintf(stderr, "Entrance_SelfCheck: non-cave door row 0x%02X was rewritten "
                          "(0x%02X -> 0x%02X)\n", d, van[d], ov[d]);
          exit(2);
        }
        continue;
      }
      uint8 want = kCaveInteriors[assign[slot_interior[d]]].entrance_ids[0];
      if (ov[d] != want) {
        fprintf(stderr, "Entrance_SelfCheck: door overlay row 0x%02X (id 0x%02X, "
                        "interior %d) = 0x%02X, want 0x%02X\n",
                d, van[d], slot_interior[d], ov[d], want);
        exit(2);
      }
    }
    // A door row belonging to a SPLIT interior must follow its own entry, not a
    // room-sibling's. Pin that directly: find two entries sharing a room and
    // confirm their rows resolve to different images whenever the permutation
    // sends those entries to different places.
    {
      int a = -1, b = -1;
      for (int i = 0; i < kEntranceCaveInteriorCount && a < 0; i++)
        for (int j = i + 1; j < kEntranceCaveInteriorCount && a < 0; j++)
          if (kCaveInteriors[i].room == kCaveInteriors[j].room &&
              assign[i] != assign[j]) { a = i; b = j; }
      if (a < 0) {
        fprintf(stderr, "Entrance_SelfCheck: expected at least one pair of split "
                        "interiors sharing a room with distinct images\n");
        exit(2);
      }
      uint8 ra = kCaveInteriors[a].door_rows[0], rb = kCaveInteriors[b].door_rows[0];
      if (ov[ra] != kCaveInteriors[assign[a]].entrance_ids[0] ||
          ov[rb] != kCaveInteriors[assign[b]].entrance_ids[0] ||
          entry_of_door_row(ra) == entry_of_door_row(rb)) {
        fprintf(stderr, "Entrance_SelfCheck: split interiors %d/%d (room 0x%03X) did "
                        "not resolve independently by door row\n",
                a, b, kCaveInteriors[a].room);
        exit(2);
      }
    }
  }

  // (8) DUNGEON pool (Stage 2). Entrance-ids unique + rooms < 0x100; entry
  //     regions resolve, are distinct, and each is the destination of EXACTLY ONE
  //     door-edge in kRandoEdges (drift guard — if the graph changes so a dungeon
  //     entry region gains/loses its single inbound edge, the edge-override key is
  //     no longer well-defined and this fires).
  {
    for (int i = 0; i < kEntranceDungeonCount; i++) {
      if (kDungeons[i].room >= 0x100) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon %d room 0x%03X not < 0x100\n",
                i, kDungeons[i].room);
        exit(2);
      }
      for (int j = i + 1; j < kEntranceDungeonCount; j++) {
        if (kDungeons[i].entrance_id == kDungeons[j].entrance_id) {
          fprintf(stderr, "Entrance_SelfCheck: duplicate dungeon entrance-id 0x%02X\n",
                  kDungeons[i].entrance_id);
          exit(2);
        }
      }
      uint16 rid = Rando_FindRegionByName(kDungeons[i].entry_region_name);
      if (rid == 0xFFFF) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon %d entry region '%s' not found\n",
                i, kDungeons[i].entry_region_name);
        exit(2);
      }
      // the edge-override array is keyed by region id and bounded by
      // kEntranceEdgeOverrideMax (64); a region id ≥ that would be silently dropped
      // on the logic side (runtime redirected, logic identity → desync). Guard it.
      if (rid >= 64) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon %d region id %u >= edge-override "
                        "bound (64); Set/GetEntranceEdgeOverride would drop it\n", i, rid);
        exit(2);
      }
      // Distinct entry regions.
      for (int j = i + 1; j < kEntranceDungeonCount; j++) {
        if (Rando_FindRegionByName(kDungeons[j].entry_region_name) == rid) {
          fprintf(stderr, "Entrance_SelfCheck: dungeons %d/%d share entry region\n", i, j);
          exit(2);
        }
      }
      // At least one inbound door-edge targets this entry region. Most dungeons
      // have exactly one; Turtle Rock and Ganon's Tower legitimately have TWO
      // (reachable from two overworld Death-Mountain contexts) — the override
      // remaps ALL edges into the region together, which is correct, so >1 is
      // allowed. 0 inbound would mean the override key is unreachable / wrong.
      int inbound = 0;
      for (uint32 e = 0; e < kRandoEdgesCount; e++) {
        if (kRandoEdges[e].to_region == rid) inbound++;
      }
      if (inbound < 1) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon %d ('%s') entry region has no "
                        "inbound door-edge — edge-override key is unreachable\n",
                i, kDungeons[i].entry_region_name);
        exit(2);
      }
      // The edge-override KEY is the INTERIOR (lobby) region (task 2.8). Validate
      // it the same way: resolves, id < 64 (edge-override array bound), and is the
      // to_region of the dungeon's GATED door edge (so the gate moves with the
      // spot). For single-region dungeons interior == entry, already checked above.
      const char *ikey = dungeon_override_key(&kDungeons[i]);
      uint16 iid = Rando_FindRegionByName(ikey);
      if (iid == 0xFFFF) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon %d interior region '%s' not found\n",
                i, ikey);
        exit(2);
      }
      if (iid >= 64) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon %d interior region id %u >= "
                        "edge-override bound (64)\n", i, iid);
        exit(2);
      }
      uint16 dd_from = 0xFFFF; uint32 dd_off = 0; uint16 dd_len = 0;
      if (!dungeon_door_edge(iid, &dd_from, &dd_off, &dd_len)) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon %d interior region '%s' is not the "
                        "to_region of any door-edge — gate would not move with the spot\n",
                i, ikey);
        exit(2);
      }
      // Interior (lobby) override keys must be mutually DISTINCT too. The
      // edge-override is keyed on the interior region, so two dungeons sharing an
      // interior key would silently double-set g_entrance_edge_override[key]
      // (last-write-wins), corrupting one dungeon's destination. Today the lobbies
      // are distinct by construction; assert it so a future logic edit can't
      // reintroduce the drift. Mirrors the entry-region distinctness check above.
      for (int j = i + 1; j < kEntranceDungeonCount; j++) {
        if (Rando_FindRegionByName(dungeon_override_key(&kDungeons[j])) == iid) {
          fprintf(stderr, "Entrance_SelfCheck: dungeons %d/%d share interior (lobby) "
                          "override key '%s'\n", i, j, ikey);
          exit(2);
        }
      }
    }
    // Pool count: base (10) without the GT opt-in, full (11) with it.
    RandoSettings ds; Settings_SetDefaults(&ds);
    ds.shuffle_dungeon_entrances = 1; ds.world_state = kWorldState_Open;
    uint8 dbase[kEntranceMaxInteriors];
    if (Entrance_ComputeDungeonPermutation(&ds, 1, 0, dbase) != kEntranceDungeonBaseCount) {
      fprintf(stderr, "Entrance_SelfCheck: base dungeon pool must be %d (GT excluded)\n",
              kEntranceDungeonBaseCount);
      exit(2);
    }
    // Turn on the Ganon's Tower opt-in for the full-pool permutation tests below.
    ds.shuffle_ganons_tower_entrance = 1;
    uint8 da[kEntranceMaxInteriors], db[kEntranceMaxInteriors];
    int dn = Entrance_ComputeDungeonPermutation(&ds, 0xBEEF, 0, da);
    if (dn != kEntranceDungeonCount) {
      fprintf(stderr, "Entrance_SelfCheck: GT-on dungeon permutation count %d (want %d)\n",
              dn, kEntranceDungeonCount);
      exit(2);
    }
    Entrance_ComputeDungeonPermutation(&ds, 0xBEEF, 0, db);
    if (memcmp(da, db, dn) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: dungeon permutation not deterministic\n");
      exit(2);
    }
    uint8 dseen[kEntranceMaxInteriors]; memset(dseen, 0, sizeof(dseen));
    for (int i = 0; i < dn; i++) {
      if (da[i] >= dn || dseen[da[i]]) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon permutation not a bijection\n");
        exit(2);
      }
      dseen[da[i]] = 1;
    }
    // Edge-override closed form: forced swap of dungeon 0 (PoD) <-> 1 (Swamp)
    // remaps each entry region to the other (verified via the getter).
    uint16 pod = Rando_FindRegionByName(kDungeons[0].entry_region_name);
    uint16 swamp = Rando_FindRegionByName(kDungeons[1].entry_region_name);
    uint8 dsw[kEntranceMaxInteriors];
    for (int i = 0; i < kEntranceDungeonCount; i++) dsw[i] = (uint8)i;
    dsw[0] = 1; dsw[1] = 0;
    Entrance_ApplyEdgeOverrides(dsw, kEntranceDungeonCount);
    if (Rando_GetEntranceEdgeOverride(pod) != swamp ||
        Rando_GetEntranceEdgeOverride(swamp) != pod) {
      fprintf(stderr, "Entrance_SelfCheck: dungeon edge-override closed form wrong\n");
      exit(2);
    }
    Entrance_ClearEdgeOverrides();
    if (Rando_GetEntranceEdgeOverride(pod) != pod) {
      fprintf(stderr, "Entrance_SelfCheck: ClearEdge must restore identity\n");
      exit(2);
    }
    // Dungeon door overlay remap + source-exit-room helper.
    uint8 dv[16], dov[16];
    for (int i = 0; i < kEntranceDungeonCount; i++) dv[i] = kDungeons[i].entrance_id;
    dv[kEntranceDungeonCount] = 0xFE;  // non-dungeon sentinel
    int dtot = kEntranceDungeonCount + 1;
    memcpy(dov, dv, dtot);
    Entrance_RemapDungeonDoors(da, dn, dov, (uint32)dtot);
    for (int i = 0; i < kEntranceDungeonCount; i++) {
      if (dov[i] != kDungeons[da[i]].entrance_id) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon door overlay slot %d wrong\n", i);
        exit(2);
      }
    }
    if (dov[kEntranceDungeonCount] != 0xFE) {
      fprintf(stderr, "Entrance_SelfCheck: non-dungeon id was rewritten\n");
      exit(2);
    }
    if (Entrance_DungeonSourceExitRoom(kDungeons[0].entrance_id) != kDungeons[0].room ||
        Entrance_DungeonSourceExitRoom(0xFE) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: dungeon source-exit-room helper wrong\n");
      exit(2);
    }
  }

  // (9) DECOUPLED (Stage 4 D.1): exit permutation is a bijection over cave holes,
  //     deterministic in (seed, attempt), inactive ⇒ empty, and the exit edges add
  //     only valid region→region warps (skipping fixed points / same-region).
  {
    RandoSettings ds = s;  // s already has shuffle_cave_entrances + Open
    ds.decoupled = 1;
    if (!Entrance_IsDecoupledActive(&ds)) {
      fprintf(stderr, "Entrance_SelfCheck: decoupled should be active for cave+Open\n");
      exit(2);
    }
    uint8 ea[kEntranceMaxInteriors], eb[kEntranceMaxInteriors];
    int en = Entrance_ComputeDecoupledExit(&ds, 0xDEC0, 0, ea);
    if (en != kEntranceCaveInteriorCount) {
      fprintf(stderr, "Entrance_SelfCheck: decoupled count %d != %d\n",
              en, kEntranceCaveInteriorCount);
      exit(2);
    }
    Entrance_ComputeDecoupledExit(&ds, 0xDEC0, 0, eb);
    if (memcmp(ea, eb, en) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: decoupled exit not deterministic\n");
      exit(2);
    }
    uint8 eseen[kEntranceMaxInteriors]; memset(eseen, 0, sizeof(eseen));
    for (int i = 0; i < en; i++) {
      if (ea[i] >= en || eseen[ea[i]]) {
        fprintf(stderr, "Entrance_SelfCheck: decoupled exit not a bijection\n");
        exit(2);
      }
      eseen[ea[i]] = 1;
    }
    // Inactive (no cave shuffle) ⇒ no permutation.
    RandoSettings dn = s; dn.decoupled = 1; dn.shuffle_cave_entrances = 0;
    uint8 e0[kEntranceMaxInteriors];
    if (Entrance_IsDecoupledActive(&dn) ||
        Entrance_ComputeDecoupledExit(&dn, 1, 0, e0) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: decoupled must be inactive without cave shuffle\n");
      exit(2);
    }
    // Regression guard (decoupled-edge-accumulation HIGH): the retry loop clears
    // edge overrides each attempt so ApplyDecoupledExitEdges Begins FRESH rather
    // than appending onto the previous attempt's edges. Lock that contract: a
    // clear+apply must add a positive, STABLE count — never grow when repeated.
    Entrance_ClearEdgeOverrides();
    Entrance_ApplyDecoupledExitEdges(ea, en);
    int dec_c1 = Rando_GetEntranceAddedEdgeCount();
    Entrance_ClearEdgeOverrides();
    Entrance_ApplyDecoupledExitEdges(ea, en);
    int dec_c2 = Rando_GetEntranceAddedEdgeCount();
    if (dec_c1 <= 0 || dec_c2 != dec_c1) {
      fprintf(stderr, "Entrance_SelfCheck: decoupled edges unstable across "
                      "clear+apply (%d then %d) — accumulation regression\n",
              dec_c1, dec_c2);
      exit(2);
    }
    Entrance_ClearEdgeOverrides();
  }

  // (10) DUNGEON DECOUPLED (Stage 4): exit permutation over the dungeon pool is a
  //      bijection, deterministic, active only for dungeon shuffle (non-cross,
  //      Open/Standard); the exit edges add a positive/stable count; and the
  //      runtime room lookup maps a loaded dungeon to net'[D]'s room.
  {
    RandoSettings dds = s;
    dds.decoupled = 1;
    dds.shuffle_dungeon_entrances = 1;
    dds.cross_category = 0;
    if (!Entrance_IsDungeonDecoupledActive(&dds)) {
      fprintf(stderr, "Entrance_SelfCheck: dungeon decoupled should be active for dungeon+Open\n");
      exit(2);
    }
    RandoSettings nod = dds; nod.shuffle_dungeon_entrances = 0;
    RandoSettings crd = dds; crd.cross_category = 1;
    uint8 z[kEntranceMaxInteriors];
    if (Entrance_IsDungeonDecoupledActive(&nod) ||
        Entrance_ComputeDungeonDecoupledExit(&nod, 1, 0, z) != 0 ||
        Entrance_IsDungeonDecoupledActive(&crd)) {
      fprintf(stderr, "Entrance_SelfCheck: dungeon decoupled needs dungeon shuffle + non-cross\n");
      exit(2);
    }
    uint8 da[kEntranceMaxInteriors], db[kEntranceMaxInteriors];
    int dnn = Entrance_ComputeDungeonDecoupledExit(&dds, 0xD00D, 0, da);
    if (dnn != Entrance_DungeonPoolCount(&dds)) {
      fprintf(stderr, "Entrance_SelfCheck: dungeon decoupled count %d != pool\n", dnn);
      exit(2);
    }
    Entrance_ComputeDungeonDecoupledExit(&dds, 0xD00D, 0, db);
    if (memcmp(da, db, dnn) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: dungeon decoupled not deterministic\n");
      exit(2);
    }
    uint8 dseen[kEntranceMaxInteriors]; memset(dseen, 0, sizeof(dseen));
    for (int i = 0; i < dnn; i++) {
      if (da[i] >= dnn || dseen[da[i]]) {
        fprintf(stderr, "Entrance_SelfCheck: dungeon decoupled not a bijection\n");
        exit(2);
      }
      dseen[da[i]] = 1;
    }
    // Runtime room lookup: loaded dungeon 0 → kDungeons[net'[0]].room (0 on self-map),
    // and a non-pool entrance-id → 0.
    int j0 = da[0];
    uint16 want = (j0 == 0) ? 0 : kDungeons[j0].room;
    if (Entrance_DungeonDecoupledExitRoom(da, dnn, kDungeons[0].entrance_id) != want ||
        Entrance_DungeonDecoupledExitRoom(da, dnn, 0x00) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: dungeon decoupled exit room lookup wrong\n");
      exit(2);
    }
  }

  // (11) CROSS DECOUPLED: pool-sized bijective permutation over the mixed pool,
  //      active only with cross + decoupled, and the runtime exit resolver maps a
  //      source door to a cave (kind 1) or dungeon (kind 2) target.
  {
    RandoSettings xc = s;
    xc.shuffle_dungeon_entrances = 1; xc.cross_category = 1; xc.decoupled = 1;
    if (!Entrance_IsCrossDecoupledActive(&xc)) {
      fprintf(stderr, "Entrance_SelfCheck: cross-decoupled should be active for cross+Open\n");
      exit(2);
    }
    RandoSettings nox = xc; nox.cross_category = 0;
    RandoSettings nod2 = xc; nod2.decoupled = 0;
    uint8 zz[kEntranceMaxInteriors];
    if (Entrance_IsCrossDecoupledActive(&nox) || Entrance_IsCrossDecoupledActive(&nod2) ||
        Entrance_ComputeCrossDecoupledExit(&nox, 1, 0, zz) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: cross-decoupled needs cross + decoupled\n");
      exit(2);
    }
    uint8 xa[kEntranceMaxInteriors], xb[kEntranceMaxInteriors];
    int xn = Entrance_ComputeCrossDecoupledExit(&xc, 0xC0FFEEull, 0, xa);
    if (xn <= kEntranceCaveInteriorCount) {  // pool = caves + >=1 cross dungeon
      fprintf(stderr, "Entrance_SelfCheck: cross-decoupled pool too small (%d)\n", xn);
      exit(2);
    }
    Entrance_ComputeCrossDecoupledExit(&xc, 0xC0FFEEull, 0, xb);
    if (memcmp(xa, xb, xn) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: cross-decoupled not deterministic\n");
      exit(2);
    }
    uint8 xseen[kEntranceMaxInteriors]; memset(xseen, 0, sizeof(xseen));
    for (int i = 0; i < xn; i++) {
      if (xa[i] >= xn || xseen[xa[i]]) {
        fprintf(stderr, "Entrance_SelfCheck: cross-decoupled not a bijection\n");
        exit(2);
      }
      xseen[xa[i]] = 1;
    }
    // Runtime resolver: cave 0's door ROW → net[0]'s endpoint kind (0 self,
    // 1 cave, 2 dun), and a row outside the door space → 0. Row-keyed, so the
    // split shop doors each get their own exit rather than sharing entry 23's.
    uint16 xval = 0;
    int t0 = xa[0];
    int want = (t0 == 0) ? 0 : ((t0 < kEntranceCaveInteriorCount) ? 1 : 2);
    if (Entrance_CrossDecoupledExit(xa, xn, kCaveInteriors[0].door_rows[0],
                                    kCaveInteriors[0].entrance_ids[0], &xval) != want ||
        Entrance_CrossDecoupledExit(xa, xn, 0xFFFF, 0x00, &xval) != 0) {
      fprintf(stderr, "Entrance_SelfCheck: cross-decoupled exit resolver wrong\n");
      exit(2);
    }
  }

  fprintf(stderr, "[Entrance_SelfCheck] OK\n");
}
