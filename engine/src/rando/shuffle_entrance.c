// Worst-case added-edge load the entrance modes can place on the shared
// logic-edge store: every cave interior gets a decoupled exit edge, and every
// dungeon (GT pool included) lands behind a cave door in cross-category.
// Consumed by OwWarp_SelfCheck's combined budget assert against
// Rando_EntranceAddedEdgeCapacity().
int Entrance_AddedEdgeWorstCase(void) {
  return kEntranceCaveInteriorCount + kEntranceDungeonCount;
}

bool Entrance_IsActive(const RandoSettings *settings) {
  if (settings == NULL) return false;
  if (!settings->shuffle_cave_entrances) return false;
  // Stage 1 supports cave shuffle on Open/Standard only. Inverted carries a
  // static per-location region override the per-seed override would clobber;
  // Retro re-uses several cave host-rooms for TakeAny. Both deferred.
  if (settings->world_state != kWorldState_Open &&
      settings->world_state != kWorldState_Standard) {
    return false;
  }
  return true;
}

// Map a raw entrance-id to A cave-interior index that carries it, or -1 if no
// entry does.
//
// AMBIGUOUS BY CONSTRUCTION — several entries may share an entrance id (the four
// Dark World shop doors are four pool entries that all load room 0x10F through
// id 0x60), and this returns the FIRST. It is therefore only sound for the
// predicate question "is this id a cave id at all". To resolve which pool entry
// a SOURCE door belongs to, use entry_of_door_row(): the door row is the
// identity unit, and every caller that resolves a source has the row in hand.
static int interior_of_entrance(uint8 ent_id) {
  for (int i = 0; i < kEntranceCaveInteriorCount; i++) {
    for (int k = 0; k < kCaveInteriors[i].entrance_count; k++) {
      if (kCaveInteriors[i].entrance_ids[k] == ent_id) return i;
    }
  }
  return -1;
}

// Map an overworld DOOR ROW (a kOverworld_Entrance_Id subscript, which is what
// every entry hook calls `lx`) to its cave-interior index, or -1 if that row is
// not a cave door. Rows partition across entries — asserted by the generator and
// by Entrance_SelfCheck (1) — so this is unambiguous where the entrance-id
// lookup above is not.
static int entry_of_door_row(uint16 lx) {
  if (lx > 0xFF) return -1;                  // door rows are u8 subscripts
  for (int i = 0; i < kEntranceCaveInteriorCount; i++) {
    for (int k = 0; k < kCaveInteriors[i].door_row_count; k++) {
      if (kCaveInteriors[i].door_rows[k] == (uint8)lx) return i;
    }
  }
  return -1;
}

int Entrance_ComputePermutation(const RandoSettings *settings, uint64 seed,
                                uint8 attempt,
                                uint8 assign[kEntranceMaxInteriors]) {
  if (assign == NULL || !Entrance_IsActive(settings)) return 0;
  const int n = kEntranceCaveInteriorCount;
  for (int i = 0; i < n; i++) assign[i] = (uint8)i;

  RandoRng rng;
  // Mix the attempt index into the seed (same constant the placer uses to
  // perturb its retry seed) so each retry draws a distinct permutation while
  // attempt 0 is a pure function of the seed (single-seed determinism).
  Rng_SeedFromU64(&rng, seed ^ ((uint64)attempt * 0x9E3779B97F4A7C15ull));
  // Fisher–Yates over the interior indices (coupled = one bijection).
  for (int i = n - 1; i > 0; i--) {
    uint32 j = Rng_NextRange(&rng, (uint32)(i + 1));
    uint8 t = assign[i]; assign[i] = assign[j]; assign[j] = t;
  }
  return n;
}

void Entrance_ApplyRegionOverrides(const uint8 *assign, int n) {
  Rando_BeginEntranceRegionOverrides();
  if (assign == NULL) return;
  // clamp the loop bound to the static table (this is a public entry
  // point; the `assign[ix]` value is already range-checked below, but the `ix`
  // index into kCaveInteriors[] must be bounded too).
  if (n > kEntranceCaveInteriorCount) n = kEntranceCaveInteriorCount;
  // For each interior ix (door fixed in vanilla region R[ix], with optional
  // source predicate P[ix]), the interior now reached through ix's door is
  // J = assign[ix]. J's locations become reachable via R[ix] AND P[ix].
  // assign is a bijection ⇒ each interior's locations are set once.
  for (int ix = 0; ix < n; ix++) {
    const RandoCaveInterior *src = &kCaveInteriors[ix];
    if (src->region_name == NULL) continue;
    uint16 region_id = Rando_FindRegionByName(src->region_name);
    if (region_id == 0xFFFF) continue;  // unknown region name — skip (no-op)
    uint32 pred_off = 0; uint16 pred_len = 0;
    cave_source_pred(ix, &pred_off, &pred_len);
    int j = assign[ix];
    if (j < 0 || j >= kEntranceCaveInteriorCount) continue;
    const RandoCaveInterior *dst = &kCaveInteriors[j];
    for (int k = 0; k < dst->location_count; k++) {
      Rando_SetEntranceRegionOverridePred(dst->location_ids[k], region_id,
                                          pred_off, pred_len);
    }
  }
}

void Entrance_ClearRegionOverrides(void) {
  Rando_ClearEntranceRegionOverrides();
}

void Entrance_BuildDoorOverlay(const uint8 *assign, int n,
                               const uint8 *vanilla, uint32 len,
                               uint8 *overlay) {
  if (vanilla == NULL || overlay == NULL) return;
  memcpy(overlay, vanilla, len);     // copy first (so a NULL assign = identity)
  if (assign == NULL) return;
  for (uint32 d = 0; d < len; d++) {
    // Resolve the SOURCE by door row, not by entrance id. `d` is the row. Keying
    // on vanilla[d] would collapse the four room-0x10F doors onto one pool entry
    // (they all carry id 0x60), which is exactly what the split exists to undo.
    int i = entry_of_door_row((uint16)d);
    if (i < 0) continue;                 // not a cave door — leave unchanged
    int j = assign[i];
    if (j < 0 || j >= kEntranceCaveInteriorCount) continue;
    // The door for interior i now loads interior j; write j's representative
    // (first) entrance-id. Coupling is handled by the engine's entry caching.
    // Several destination entries legitimately share that id — they are the same
    // physical room reached through different doors, so the write is correct.
    overlay[d] = kCaveInteriors[j].entrance_ids[0];
  }
  (void)n;
}

