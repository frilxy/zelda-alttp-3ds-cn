// Paid delivery transaction hooks. Prepare selects the first undiscovered,
// unchecked target (or Exhausted), fully encodes the locale-aware presentation
// into epoch-bound scratch, and does not mutate discovery. Commit revalidates
// that exact armed selection and marks it discovered. Reload/replay or another
// epoch change clears the transient latch, so Commit fails and the owning
// handler applies its refund path. Cancel ends the repeated-message latch.
bool Rando_HintsPreparePaid(RandoHintPaidSource source);
bool Rando_HintsCommitPaid(RandoHintPaidSource source);
void Rando_HintsCancelPaid(RandoHintPaidSource source);
// Read-only availability probe used to frame paid service choices truthfully.
// It follows the same discovery/checked-target scan as Prepare but never arms
// presentation state or changes discovery.
bool Rando_HintsPaidHasClue(RandoHintPaidSource source);
// Set the source/price context for the next paid Yes/No prompt. The messaging
// post-decode hook uses it only when no clue is available, replacing the
// vanilla "tip/reading" claim with localized price + healing-only framing.
void Rando_HintsSetPaidPromptContext(RandoHintPaidSource source, uint16 price);

// Returns the stable dialogue label for a source with a primary assignment.
uint16 Rando_GetHintDialogueId(RandoHintNpc npc);

// Retrieve the complete human-readable PRIMARY hint text for compatibility
// spoiler output. Paid reserves are enumerated through Rando_GetHintFact.
const char *Rando_GetHintString(RandoHintNpc npc);

// Returns the ALTTPR-compatible string-ID for `npc` (e.g., `kRandoHintNpc_TeleEasternPalace`
// → `"telepathic_tile_eastern_palace"`). Used by the spoiler-JSON
// emitter to produce keys that diff cleanly against ALTTPR seeds.
// Returns NULL for invalid npc.
const char *Rando_GetHintNpcStringId(RandoHintNpc npc);

// Clear plan, discovery, imported expectation, and pending paid transactions.
void Rando_ClearHints(void);

// ---------------------------------------------------------------------------
// Telepathic-tile runtime dispatch.
//
// The 15 ALTTPR telepathic-tile hints surface in-game by hijacking the
// VANILLA per-room telepathic-tile dialogue ids. Link reading a tile sets
// `dialogue_message_index` (player.c::Link_PerformRead -> Dungeon_GetTeleMsg)
// to one of the 15 vanilla US tele-message ids; the messaging engine
// (messaging.c::Text_LoadCharacterBuffer) calls Rando_RenderHintMessage at
// its top to give this module first refusal on those ids.
//
// The 15 hint-bearing vanilla US tele-message ids are:
//   0xB4, 0xB5, 0xB8, 0xB9, 0xBA, 0xBB, 0xBE, 0xBF, 0xC0, 0xC1, 0xC2,
//   0xC3, 0xC4, 0xC5, 0xC6
// (0xB4 is the Eastern Palace tile, the first ALTTPR tile; 0xC7 is the Chris
// Houlihan secret room and is NOT a hint tile. See kHintTileMsgIds in
// rando_hints.c for the off-by-one this corrects.) These ids map positionally
// to the 15
// RandoHintNpc telepathic-tile slots: each distinct physical tile shows one
// distinct generated hint. The exact tile<->hint pairing need not byte-match
// ALTTPR because ALTTPR itself fy_shuffles the tile list (HintService.php:59)
// — the generator's per-tile assignment is already a deterministic shuffle.
// ---------------------------------------------------------------------------

// True when `msg_id` is one of the 15 hint-bearing vanilla telepathic-tile
// message ids above (0xB4 the Eastern Palace tile IS included; 0xC7 the Chris
// Houlihan room is excluded). Pure predicate; does
// NOT consult the active hint table or rando-active state.
bool Rando_IsHintTileMessage(uint16 msg_id);

// Generated-hint and non-interactive vanilla-dialogue interception. Called at
// the very top of Text_LoadCharacterBuffer. Owned hint surfaces are always
// intercepted for an active randomizer slot: ready plans render the assigned
// fact, while Off/missing/unsupported/mismatch/exhausted states render truthful
// locale-aware neutral text. On true, writes font-encoded character codes
// (the messaging engine's `messaging_text_buffer`, >=256 bytes), laid out as
// up to three message-box lines and terminated with the 0x7f end marker the
// renderer expects, then resets `dialogue_msg_read_pos`. Returns false in
// every other case so the vanilla dialogue decode proceeds unchanged.
bool Rando_RenderHintMessage(uint16 msg_id, uint8 *out_buffer);

// Post-decode companion for choice surfaces. Stumpy/Flute Boy uses the same
// resolver/gates as Rando_RenderHintMessage and receives a hint/neutral page
// followed by its preserved choice. Current-schema paid services also use this
// hook when no clue is available, receiving localized no-clue + exact-price +
// healing-only framing before their preserved choice. Frozen schema 1 retains
// its original bytes. Returns false without modifying the buffer for
// non-owned/inapplicable messages.
bool Rando_RewriteInteractiveHintMessage(uint16 msg_id, uint8 *out_buffer);

// True when `msg_id` is a confirmed vanilla-dialogue redirect owned by the
// active slot and its context discriminator matches. Hints Off or unavailable
// identity still counts as owned because the surface renders neutral text
// rather than a false vanilla placement claim.
// Pure/read-only: it never renders or mutates the hint table/buffer.
// Used by both Rando_RenderHintMessage and story-dialogue fast-forward policy.
bool Rando_IsDynamicHintMessage(uint16 msg_id);

// Unrestricted spoiler-bearing dev diagnostic: dump live/expected/computed plan
// identity, discovery, assignments, queues, and text to dump_hints.txt even for
// a race slot (called from ZeldaDumpDebugState / F12). `cur_msg_id` is the
// current dialogue_message_index.
void Rando_DumpHintDebug(uint16 cur_msg_id);

// Full deterministic plan, exact-rendering, discovery, paid-queue,
// persistence-identity, locale-neutral, and redirect regression self-check.
void Hints_SelfCheck(void);

