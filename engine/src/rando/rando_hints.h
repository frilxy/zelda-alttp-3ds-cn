// ---------------------------------------------------------------------------
// Settings axis: public Off/Balanced mode (binary on disk, matching ALTTPR
// `spoil.Hints` at `HintService.php:54` which tests `=== 'on'`).
//
// The stable enum value occupies canonical byte 22 (joined the settings hash
// at kGeneratorVersion 14); see Settings_CanonicalSerialize/Deserialize in
// rando_settings.c.
// ---------------------------------------------------------------------------
typedef enum RandoHintsMode {
  kHintsMode_Off = 0,
  // Serialized value 1 historically appeared as on/full/sahasrahla. Hints v2
  // normalizes every such public alias to the one supported Balanced mode.
  kHintsMode_Balanced = 1,
  kHintsMode_On = kHintsMode_Balanced,
} RandoHintsMode;

// ---------------------------------------------------------------------------
// Immutable plan and mutable discovery state.
//
// New saves persist the algorithm/text-schema versions and the SHA-256 digest
// of the complete ordered plan. A loader must select that exact algorithm and
// verify the digest; missing, unsupported, or mismatched metadata fails hints
// closed with neutral owned-surface text. Full deck bytes are reconstructed,
// never serialized.
// ---------------------------------------------------------------------------
#define kRandoHintPlanLegacyAlgorithmVersion 1u
#define kRandoHintLegacyTextSchemaVersion    1u
#define kRandoHintPlanAlgorithmVersion       4u
#define kRandoHintTextSchemaVersion          4u
// Generator 156 minted the frozen 1/1 spoiler schema; generator 157 was the
// first schema-bearing feature-line version with configurable policy plus the
// additive 2/2 spoiler fields. The 157 constant is therefore a historical
// schema floor, not the current generator version. Race reveal retains an
// explicit frozen-156 compatibility path while every other non-current
// generator remains unsupported.
#define kRandoHintLegacyGeneratorVersion     156u
#define kRandoHintConfigurableGeneratorVersion 157u
#define kRandoHintPlanDigestBytes      32u
#define kRandoHintPlanMaxFacts         24u
#define kRandoHintPlanPrimaryTarget    18u
#define kRandoHintPaidSourceCount      3u
#define kRandoHintPaidQueueCapacity    3u
#define kRandoHintDiscoveryBytes       4u
#define kRandoHintNoFact               0xFFu

