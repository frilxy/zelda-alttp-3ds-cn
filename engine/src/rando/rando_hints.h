typedef struct RandoHintFact {
  uint8 fact_id;
  uint8 kind;
  uint8 template_id;
  uint8 primary;
  uint16 location_id;  // 0xFFFF for non-placement facts.
  uint16 item_id;      // 0xFFFF for non-placement facts.
  uint16 region_id;    // 0xFFFF when not region-scoped.
  // Stable template-specific semantic payload: Goal enum, active-setting
  // subject id, literal region-value count, or flavor id. Zero for exact
  // placement facts. Rendered/localized strings are not part of plan identity.
  uint16 template_parameter;
  char text[160];      // complete human-readable journal/spoiler text.
  char game_text[96];  // complete, verified three-row in-game rendering.
} RandoHintFact;

typedef struct RandoHintPlan {
  uint16 algorithm_version;
  uint16 text_schema_version;
  uint8 mode;
  // Normalized seed policy. Enabled legacy 1/1 plans carry the compatibility
  // defaults (15 tiles, Variety, three clues per paid service); legacy Off is
  // empty. Algorithm 2 binds these values into its semantic digest before
  // facts/assignments.
  uint8 tile_target;
  uint8 mix;
  uint8 paid_depth;
  uint8 fact_count;
  uint8 primary_fact_by_npc[kRandoHintNpc__Count];
  uint8 paid_queue[kRandoHintPaidSourceCount][kRandoHintPaidQueueCapacity];
  uint8 paid_count[kRandoHintPaidSourceCount];
  uint8 murahdahla_active;
  uint8 digest[kRandoHintPlanDigestBytes];
  char murahdahla_text[160];
  RandoHintFact facts[kRandoHintPlanMaxFacts];
} RandoHintPlan;

typedef struct RandoHintPersistedState {
  uint16 algorithm_version;  // 0 means metadata absent.
  uint16 text_schema_version;
  uint8 plan_digest[kRandoHintPlanDigestBytes];
  uint8 discovered[kRandoHintDiscoveryBytes];
} RandoHintPersistedState;

// ---------------------------------------------------------------------------
// Dialogue-ID labels.
//
// `kRandoHintDialogueBase + (RandoHintNpc - 1)` gives each hint NPC a stable
// 16-bit spoiler label, positionally mapped. It is NOT a runtime dialogue
// carve. The in-game intercept does not key off this range:
// `Text_LoadCharacterBuffer` calls `Rando_RenderHintMessage`, which replaces
// the vanilla tile text in place when the requested `dialogue_message_index`
// is one of the 15 vanilla telepathic-tile message IDs (`kHintTileMsgIds`,
// 0xB4,0xB5,0xB8..0xBB,0xBE..0xC6 — 0xB4 IS the Eastern Palace tile and is
// included; 0xC7 = Chris Houlihan room and is excluded; see the array's comment
// in rando_hints.c). `Rando_RemapTeleMsg` is a compatibility no-op and is not
// used by the runtime intercept.
// ---------------------------------------------------------------------------
#define kRandoHintDialogueBase  0x200u
#define kRandoHintDialogueCount 20u  // = kRandoHintNpc__Count - 1
#define kRandoHintDialogueEnd   (kRandoHintDialogueBase + kRandoHintDialogueCount)

// Legacy compatibility no-op retained for out-of-tree callers. Runtime
// interception replaces the 15 verified vanilla message IDs in
// Rando_RenderHintMessage and does not carve a synthetic dialogue range.
uint16 Rando_RemapTeleMsg(uint16 vanilla_id, uint16 room_or_area, bool is_overworld);

// Read-only, main-thread caller-owned builder used by generation, spoilers,
// race reveal, and the active-slot installer. It never mutates the live
// plan/discovery/paid state, but it consumes the currently installed effective
// entrance-region overlay; callers must build before clearing that overlay.
// Requested settings are canonicalized internally to the exact effective
// settings image persisted and recovered at activation.
// `spheres` is reserved for compatible future algorithm versions; the current
// algorithm intentionally derives no plan identity from mutable sphere output.
bool Rando_BuildHintPlan(const RandoSettings *settings,
                         const RandoPlacementTable *placements,
                         const RandoSpheres *spheres,
                         uint16 algorithm_version,
                         uint16 text_schema_version,
                         RandoHintPlan *out);

// Compatibility helper: build and install a fresh current plan with discovery
// cleared. Active gameplay reconstruction uses Rando_RebuildHints instead.
bool Rando_GenerateHints(const RandoSettings *settings,
                         const RandoPlacementTable *placements,
                         const RandoSpheres *spheres);

// Reconstruct an ACTIVE slot plan from the current persisted 2/2 state most
// recently supplied to Rando_HintsImportPersistedState. Missing, legacy,
// unsupported, or mismatched metadata returns true after installing a
// fail-closed neutral plan status; it never guesses a different plan. A
// structural build failure returns false. The frozen 1/1 builder is direct
// race-reveal compatibility, not a sidecar/snapshot format.
bool Rando_RebuildHints(const RandoSettings *settings,
                        const RandoPlacementTable *placements,
                        const RandoSpheres *spheres);

// Install the persisted identity/discovery expectation used by the next
// Rando_RebuildHints call. NULL means metadata is missing (fail closed).
void Rando_HintsImportPersistedState(const RandoHintPersistedState *state);

// Export the current live 2/2 plan identity + discovery. Returns true for a
// verified Ready plan or the certified empty Off plan; legacy,
// unavailable/mismatched state is never persisted as a newly blessed identity.
bool Rando_HintsExportPersistedState(RandoHintPersistedState *out);
bool Rando_HintPlanExportPersistedState(const RandoHintPlan *plan,
                                        RandoHintPersistedState *out);

RandoHintPlanStatus Rando_GetHintPlanStatus(void);
