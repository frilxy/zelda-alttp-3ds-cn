#!/usr/bin/env python3
"""Encode the attributed MIT randomizer art without changing base asset files."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]


def main():
    image = Image.open(ROOT / 'engine/assets/rando/custom_item_gfx.png')
    if image.mode != 'P' or image.size != (16, 128):
        raise ValueError('Expected eight indexed 16x16 cells')
    pixels = image.tobytes()
    if any(p > 15 for p in pixels):
        raise ValueError('Palette index exceeds SNES 4bpp range')
    data = bytearray()
    for cell in range(8):
        for tile_y in range(2):
            for tile_x in range(2):
                tile = bytearray(32)
                for y in range(8):
                    for x in range(8):
                        value = pixels[(cell * 16 + tile_y * 8 + y) * 16 + tile_x * 8 + x]
                        for bit in range(4):
                            tile[y * 2 + (bit & 1) + (bit // 2) * 16] |= ((value >> bit) & 1) << (7 - x)
                data.extend(tile)
    lines = [
        '// Generated by tools/randomizer/encode_custom_art.py.',
        '// MIT custom art: see rando/upstream/NOTICE. No base ROM graphics.',
        '#pragma once', '#include "../types.h"',
        'static const uint8 kRandoCustomItemGfx[] = {'
    ]
    lines += ['  ' + ', '.join('0x%02x' % b for b in data[i:i+16]) + ','
              for i in range(0, len(data), 16)]
    lines += ['};', '#define kRandoCustomItemGfx_SIZE sizeof(kRandoCustomItemGfx)', '']
    output = ROOT / 'engine/src/rando/custom_item_gfx.h'
    output.write_text('\n'.join(lines))
    print(f'Wrote {len(data)} bytes of attributed custom art')


if __name__ == '__main__':
    main()
