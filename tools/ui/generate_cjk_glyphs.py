#!/usr/bin/env python3
"""Generate engine/src/ui_glyphs_cjk.h: the Chinese glyphs the port's own
screens need, at the three sizes those screens use.

The bottom screen draws Latin at three scales, each with its own pixel size.
Chinese gets the same treatment, with the fonts the project picked:
Fusion Pixel for the small sizes and GNU Unifont for the large one.

  10 px  Fusion Pixel   scale 1
  12 px  Fusion Pixel   scale 3
  16 px  GNU Unifont    scale 2

The fonts are OFL and are not committed (they are several megabytes); pass
--font-dir, and see docs in tools/ui/README.md for where to get them:

  unifont-18.0.01.otf
  fusion-pixel-12px-monospaced-zh_hans.ms.bitmap.ttf
  fusion-pixel-10px-monospaced-zh_hans.ms.bitmap.ttf

Run from the repository root:

  python3 tools/ui/generate_cjk_glyphs.py --font-dir /path/to/fonts
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SIZES = {
    10: 'fusion-pixel-10px-monospaced-zh_hans.ms.bitmap.ttf',
    12: 'fusion-pixel-12px-monospaced-zh_hans.ms.bitmap.ttf',
    16: 'unifont-18.0.01.otf',
}
# Every codepoint the port's own screens can print outside Latin. Anything
# below this is drawn by the existing Latin/Cyrillic font.
FIRST_CJK = 0x2E80

SOURCES = (
    'engine/src/ui_strings.c',
    'platform/3ds/source/game_languages.h',
)


def collect_chars(root: Path) -> list[str]:
    chars: set[str] = set()
    for name in SOURCES:
        text = (root / name).read_text(encoding='utf-8')
        for ch in text:
            if ord(ch) >= FIRST_CJK:
                chars.add(ch)
    return sorted(chars)


def render(font: ImageFont.FreeTypeFont, ch: str, size: int) -> list[int]:
    """One glyph as rows of bits, most significant bit leftmost, ink centred."""
    box = size + size // 2
    image = Image.new('L', (box, box), 0)
    draw = ImageDraw.Draw(image)
    draw.text((box // 4, box // 4), ch, font=font, fill=255, anchor='lt')
    ink = image.getbbox()
    if ink is None:
        return [0] * size
    image = image.crop(ink)
    width = min(image.width, size)
    height = min(image.height, size)
    left = (size - width) // 2
    top = (size - height) // 2
    rows = []
    for y in range(size):
        bits = 0
        if 0 <= y - top < height:
            for x in range(size):
                if 0 <= x - left < width:
                    if image.getpixel((x - left, y - top)) > 127:
                        bits |= 1 << (size - 1 - x)
        rows.append(bits)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--font-dir', type=Path, default=Path('fonts'))
    parser.add_argument('--check', action='store_true',
                        help='fail when the generated header would change')
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[2]
    chars = collect_chars(root)
    if not chars:
        raise SystemExit('no Chinese characters found in the UI strings')

    fonts = {}
    for size, name in SIZES.items():
        path = args.font_dir / name
        if not path.exists():
            raise SystemExit(f'missing font {path} (see --font-dir)')
        fonts[size] = ImageFont.truetype(str(path), size)

    glyphs = {size: [render(fonts[size], ch, size) for ch in chars] for size in SIZES}

    out = [
        '// Generated by tools/ui/generate_cjk_glyphs.py. Do not edit.',
        '#pragma once',
        '#include <stdint.h>',
        '',
        f'// {len(chars)} characters, sorted by codepoint. Chinese text on the port\'s',
        '// own screens; the Latin and Cyrillic letters live in ui_glyphs_intl.h.',
        f'#define kUiCjkGlyphCount {len(chars)}',
        f'#define kUiCjkFirstCodepoint 0x{FIRST_CJK:X}',
        '',
        'static const uint32_t kUiCjkCodepoints[kUiCjkGlyphCount] = {',
    ]
    out += [f'  0x{ord(ch):04x},' for ch in chars]
    out.append('};')
    for size in (10, 12, 16):
        out.append('')
        out.append(f'// {size}x{size}, one row per line, most significant bit leftmost.')
        out.append(f'static const uint16_t kUiCjk{size}[kUiCjkGlyphCount][{size}] = {{')
        for ch, rows in zip(chars, glyphs[size]):
            out.append('  {%s},  // %s U+%04X' % (','.join(str(r) for r in rows), ch, ord(ch)))
        out.append('};')
    rendered = '\n'.join(out) + '\n'

    target = root / 'engine/src/ui_glyphs_cjk.h'
    if args.check:
        current = target.read_text(encoding='utf-8') if target.exists() else ''
        if current != rendered:
            raise SystemExit(f'{target} is out of date; rerun the generator')
        print(f'{target.name} is up to date ({len(chars)} glyphs)')
        return
    target.write_text(rendered, encoding='utf-8')
    print(f'wrote {target} ({len(chars)} glyphs, {len(rendered) // 1024} KB)')


if __name__ == '__main__':
    main()
