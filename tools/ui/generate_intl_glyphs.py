#!/usr/bin/env python3
"""Generate engine/src/ui_glyphs_intl.h: the 5x7 capitals the port's own
screens need beyond Latin. Each row is five bits, leftmost pixel in bit 4,
drawn on the same grid as the Latin letters of the setup and native fonts.

Run from the repository root:  python3 tools/ui/generate_intl_glyphs.py
"""
from pathlib import Path

# U+0410..U+042F, А..Я. Letters shared with Latin reuse its exact shapes.
CYRILLIC = {
    'А': [14, 17, 17, 31, 17, 17, 17], 'Б': [31, 16, 16, 30, 17, 17, 30],
    'В': [30, 17, 17, 30, 17, 17, 30], 'Г': [31, 16, 16, 16, 16, 16, 16],
    'Д': [6, 10, 10, 10, 10, 31, 17],  'Е': [31, 16, 16, 30, 16, 16, 31],
    'Ж': [21, 21, 21, 14, 21, 21, 21], 'З': [14, 17, 1, 6, 1, 17, 14],
    'И': [17, 17, 19, 21, 25, 17, 17], 'Й': [17, 17, 19, 21, 25, 17, 17],
    'К': [17, 18, 20, 24, 20, 18, 17], 'Л': [7, 9, 9, 9, 9, 9, 17],
    'М': [17, 27, 21, 21, 17, 17, 17], 'Н': [17, 17, 17, 31, 17, 17, 17],
    'О': [14, 17, 17, 17, 17, 17, 14], 'П': [31, 17, 17, 17, 17, 17, 17],
    'Р': [30, 17, 17, 30, 16, 16, 16], 'С': [14, 17, 16, 16, 16, 17, 14],
    'Т': [31, 4, 4, 4, 4, 4, 4],       'У': [17, 17, 17, 15, 1, 17, 14],
    'Ф': [4, 14, 21, 21, 21, 14, 4],   'Х': [17, 17, 10, 4, 10, 17, 17],
    'Ц': [18, 18, 18, 18, 18, 31, 1],  'Ч': [17, 17, 17, 15, 1, 1, 1],
    'Ш': [21, 21, 21, 21, 21, 21, 31], 'Щ': [21, 21, 21, 21, 21, 31, 1],
    'Ъ': [24, 8, 8, 14, 9, 9, 14],     'Ы': [17, 17, 17, 29, 19, 19, 29],
    'Ь': [16, 16, 16, 30, 17, 17, 30], 'Э': [14, 17, 1, 7, 1, 17, 14],
    'Ю': [18, 21, 21, 29, 21, 21, 18], 'Я': [15, 17, 17, 15, 5, 9, 17],
}


def generate():
    letters = [chr(0x410 + i) for i in range(32)]
    assert sorted(CYRILLIC) == sorted(letters)
    for rows in CYRILLIC.values():
        assert len(rows) == 7 and all(0 <= r < 32 for r in rows)
    out = ['// Generated by tools/ui/generate_intl_glyphs.py. Edit its patterns.',
           '#pragma once', '#include <stdint.h>', '',
           '// U+0410..U+042F (А..Я); lower case and Ё/ё map onto these.',
           '// Й and Ё add the breve and diaeresis marks above the letter.',
           'static const uint8_t kUiCyrillic5x7[32][7] = {']
    for ch in letters:
        out.append('  {%s},  // U+%04X' % (','.join('%2d' % r for r in CYRILLIC[ch]), ord(ch)))
    out += ['};', '']
    return '\n'.join(out)


def main():
    path = Path(__file__).resolve().parents[2] / 'engine/src/ui_glyphs_intl.h'
    path.write_text(generate())
    print('wrote', path)


if __name__ == '__main__':
    main()
