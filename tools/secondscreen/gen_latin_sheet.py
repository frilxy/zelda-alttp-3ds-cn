#!/usr/bin/env python3
"""Regenerate app/jni/src/src/ss_latin_data.h, the bottom-screen Latin atlas.

The bottom screen used to take its digits and A-Z from the game's own 8x8 tile
font, which cannot be scaled and sits badly next to 16px CJK.  This bakes them
from GNU Unifont instead -- the same face the CJK atlas now uses, whose Latin is
a half-width 8x16 design sharing the CJK em box, so both scripts come from one
typeface and share a baseline.

Encoding matches gen_cjk_atlas.py: an 8x16 cell, 2bpp, 0 = transparent,
1 = outline, 2 = body, two bytes per row, 32 bytes per glyph.

Usage:
    gen_latin_sheet.py [--font PATH] [--check]

    Requires Python 3 and Pillow.

    --check  only report whether ss_latin_data.h is up to date; write nothing.
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "app", "jni", "src", "src", "ss_latin_data.h")
DEFAULT_FONT = os.path.join(ROOT, "fonts", "unifont-18.0.01.otf")

# draw_text() folds lower case to upper case, so upper case only.  The order is
# "0-9 then A-Z" and kSS_Text*Cell in ss_sheets.h indexes it.
CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"

CELL_W = 8
CELL_H = 16
BOX = 16          # Unifont's native bitmap strike; any other size renders empty
BODY = 2
OUTLINE = 1


def render(font, ch):
    from PIL import Image, ImageDraw
    img = Image.new("L", (CELL_W, CELL_H), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    px = img.load()
    out = bytearray(CELL_W * CELL_H // 4)
    for y in range(CELL_H):
        for x in range(CELL_W):
            v = px[x, y]
            if v <= 0:
                continue
            out[y * (CELL_W // 4) + x // 4] |= (BODY if v >= 128 else OUTLINE) << ((3 - (x % 4)) * 2)
    return bytes(out)


def c_escape(data):
    parts = []
    for b in data:
        if b == 0x22:
            parts.append('\\"')
        elif b == 0x5C:
            parts.append("\\\\")
        elif 0x20 <= b < 0x7F:
            parts.append(chr(b))
        else:
            parts.append("\\x%02x" % b)
    return "".join(parts)


def build(font_path):
    from PIL import ImageFont
    font = ImageFont.truetype(font_path, BOX)
    chars = list(CHARS)
    glyphs = [render(font, ch) for ch in chars]
    for ch, g in zip(chars, glyphs):
        if not any(g):
            raise SystemExit(f"{ch!r} rendered empty -- is {font_path} the native size?")
    lines = [
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "// Bottom-screen Latin glyph atlas: digits then A-Z, baked from GNU Unifont's",
        "// native 16px bitmap strike.  Unifont's Latin is a half-width 8x16 design that",
        "// shares the CJK em box, so it lines up with the 16x16 CJK atlas.",
        "// 8x16 2bpp cell (0=transparent, 1=outline, 2=body), 32 bytes per glyph.",
        "// Generated by tools/secondscreen/gen_latin_sheet.py -- do not edit by hand.",
        "enum { kSSLatinCount = %d };" % len(chars),
        'static const char kSSLatinChars[kSSLatinCount+1] = "%s";' % c_escape("".join(chars).encode("utf-8")),
        "static const uint8_t kSSLatinGlyphs[kSSLatinCount*%d] = {" % len(glyphs[0]),
    ]
    for g in glyphs:
        lines.append("  " + ", ".join("0x%02x" % b for b in g) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if not os.path.exists(args.font):
        sys.exit(f"font not found: {args.font}")
    text = build(args.font)

    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current == text:
            print(f"ss_latin_data.h is up to date ({len(CHARS)} glyphs)")
            return 0
        print("ss_latin_data.h is OUT OF DATE -- re-run gen_latin_sheet.py")
        return 1

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(CHARS)} glyphs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
